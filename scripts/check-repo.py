"""Check the repository's file rules.

- no two tracked or untracked-but-not-ignored paths that differ only in case
- no symlinks
- text files have LF line endings (KEEP_CRLF excepted) and no NUL bytes
- every file LapinLibre owns names its licence in an SPDX-License-Identifier line within its first
  five lines: GPL-2.0-only in kernel/, GPL-2.0-or-later in system/external/, MIT
  elsewhere. Not marked (LICENSES/ and README.md say how they are licensed): patches, which are
  under the licence of what they patch; the licence texts; test data and recorded test output;
  files whose readers take no comments.

Exits 1 and lists the problems if any rule is broken.
"""

import fnmatch
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BINARY_SUFFIXES = {".png", ".jpg", ".mp3", ".gz", ".tar", ".zip", ".gpg"}
# Kept byte for byte: Violet's signed file, whose lines end in CRLF.
KEEP_CRLF = {"image/usbkey/autorun.sig"}

# Files with no SPDX line, and why (fnmatch patterns, "*" crossing "/").
UNMARKED = [
    ("*.patch", "under the licence of what it patches"),
    ("LICENSES/*", "the licence texts"),
    ("kernel/COPYING", "the kernel's licence text"),
    ("tests/expected/*.txt", "recorded test output"),
    ("tests/data/*", "test data"),
    ("*.json", "JSON takes no comments"),
    ("*.lock", "generated by uv"),
    ("system/external/external.desc", "Buildroot reads it line by line"),
    ("image/usbkey/autorun.sig", "Violet's signed file; the factory system runs a stick's autorun only beside it"),
    ("image/core/rootfs/karotz/etc/passwd", "the account database takes no comments"),
    ("image/core/rootfs/karotz/etc/group", "the account database takes no comments"),
    ("image/core/rootfs/karotz/etc/rootfs_version", "read whole by the installer"),
    ("image/core/rootfs/karotz/etc/motd", "shown as it is"),
    ("image/core/rootfs/karotz/etc/shells", "the login shells' list, read line by line"),
    ("image/core/rootfs/karotz/etc/ld.so.conf", "ldconfig's list"),
    ("image/core/usr/etc/conf/karotz.conf", "the controller's settings reader"),
    ("image/core/usr/etc/conf/voice.conf", "voice-daemon's settings reader"),
]


def licence_for(path):
    """The SPDX licence a file of LapinLibre's must name, or None if it is unmarked."""
    if any(fnmatch.fnmatchcase(path, pattern) for pattern, _ in UNMARKED):
        return None
    if path.startswith("kernel/"):
        return "GPL-2.0-only"
    if path.startswith("system/external/"):
        return "GPL-2.0-or-later"
    return "MIT"


def repository_files():
    out = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT, check=True, capture_output=True,
    ).stdout
    return sorted({p for p in out.decode().split("\0") if p})


def main():
    problems = []
    files = repository_files()
    by_lower = defaultdict(list)
    for path in files:
        by_lower[path.lower()].append(path)
        full = ROOT / path
        if full.is_symlink():
            problems.append(f"{path}: symlink")
            continue
        if not full.is_file() or full.suffix in BINARY_SUFFIXES:
            continue
        data = full.read_bytes()
        if b"\0" in data:
            problems.append(f"{path}: binary content")
        elif b"\r\n" in data and path not in KEEP_CRLF:
            problems.append(f"{path}: CRLF line endings")
        licence = licence_for(path)
        if licence is not None:
            head = b"\n".join(data.split(b"\n", 5)[:5])
            if f"SPDX-License-Identifier: {licence}".encode() not in head:
                problems.append(f"{path}: no SPDX-License-Identifier: {licence} in its first five lines")
    for paths in by_lower.values():
        if len(paths) > 1:
            problems.append("paths differ only in case: " + ", ".join(paths))
    for problem in problems:
        print(problem, file=sys.stderr)
    print(f"check-repo: {len(files)} files, {len(problems)} problems", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
